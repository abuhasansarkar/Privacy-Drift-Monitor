/*
 * ⚠️ ADAPTED TO THIS REPO'S `Button`, NOT SHIPPED AS GENERATED.
 *
 * shadcn's version renders `<Button variant="default" size="default" asChild>`
 * wrapping the Radix primitive. Ours is a hand-written Button whose variants
 * are `primary | secondary | ghost | danger` and sizes `sm | md` (§11.4 maps
 * shadcn's `default` onto our `primary`), and it does not implement `asChild` —
 * it renders a real `<button>`. Passing shadcn's names through was a type error
 * on three lines and would have been a runtime no-op on `asChild`.
 *
 * Rather than replace our Button — 23 call sites use `variant="primary"`, and
 * its exhaustive-map design is deliberate (see the file header) — the primitive
 * carries the classes directly. `buttonClasses` is the same string builder the
 * Button itself uses, so these stay visually identical to every other button
 * without either file knowing about the other's internals.
 */
function AlertDialogAction({
  className,
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Action>) {
  return (
    <AlertDialogPrimitive.Action
      data-slot="alert-dialog-action"
      className={cn(buttonClasses("primary", "md"), className)}
      {...props}
    />
  )
}

function AlertDialogCancel({
  className,
  ...props
}: React.ComponentProps<typeof AlertDialogPrimitive.Cancel>) {
  return (
    <AlertDialogPrimitive.Cancel
      data-slot="alert-dialog-cancel"
      className={cn(buttonClasses("secondary", "md"), className)}
      {...props}
    />
  )
}

